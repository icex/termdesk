package trust

import (
	"os"
	"path/filepath"
	"testing"
)

func TestTrustBindsPathAndExactLoadedBytes(t *testing.T) {
	t.Setenv("TERMDESK_CONFIG_PATH", filepath.Join(t.TempDir(), "config.toml"))
	path := filepath.Join(t.TempDir(), ".termdesk.toml")
	original := []byte("command = \"echo\"\n")
	os.WriteFile(path, original, 0600)
	if IsTrusted(path) {
		t.Fatal("file starts trusted")
	}
	if err := Record(path); err != nil {
		t.Fatal(err)
	}
	if !IsTrustedData(path, original) {
		t.Fatal("approval lost")
	}
	changed := []byte("command = \"sh\"\n")
	os.WriteFile(path, changed, 0600)
	if IsTrusted(path) || IsTrustedData(path, changed) {
		t.Fatal("changed contents inherit trust")
	}
	// Recording generated bytes must not approve a replacement from another writer.
	if err := RecordData(path, original); err != nil {
		t.Fatal(err)
	}
	if IsTrusted(path) {
		t.Fatal("concurrent replacement was approved")
	}
}
